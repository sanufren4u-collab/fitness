export function isLocale(value: string | null | undefined): value is Locale {
  return locales.includes(value as Locale);
}

export function intlLocale(locale: Locale) {
  if (locale === 'hi') return 'hi-IN';
  if (locale === 'ne') return 'ne-NP';
  return 'en-IN';
}

export function translate(
  locale: Locale,
  message: string,
  values?: Record<string, string | number>,
) {
  const translated = locale === 'en' ? message : translations[locale][message] ?? message;
  if (!values) return translated;
  return translated.replace(/\{(\w+)\}/g, (placeholder, key: string) =>
    typeof values[key] === 'number'
      ? new Intl.NumberFormat(intlLocale(locale)).format(values[key] as number)
      : String(values[key] ?? placeholder),
  );
}